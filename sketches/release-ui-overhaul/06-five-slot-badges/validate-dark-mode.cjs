const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const {JSDOM,VirtualConsole}=require('jsdom');
const source=fs.readFileSync(path.join(__dirname,'index.html'),'utf8');
const errors=[],vc=new VirtualConsole();vc.on('jsdomError',error=>errors.push(error));
const media={matches:false,addEventListener(){},removeEventListener(){}};
const dom=new JSDOM(source,{runScripts:'dangerously',url:'https://preview.test/dark-mode',pretendToBeVisual:true,virtualConsole:vc,beforeParse(window){window.matchMedia=()=>media;window.localStorage.setItem('dreamworld:appearance','dark')}});
const d=dom.window.document,nextTurn=()=>new Promise(resolve=>dom.window.setTimeout(resolve,0));
(async()=>{
  await nextTurn();
  const rootStyle=dom.window.getComputedStyle(d.documentElement);
  assert.equal(rootStyle.getPropertyValue('--canvas').trim(),'#0b0d0b','final v4 dark canvas token drifted');
  assert.equal(rootStyle.getPropertyValue('--card').trim(),'#171a17','final v4 dark card token drifted');
  assert.equal(rootStyle.getPropertyValue('--bluegray').trim(),'#202927','final v4 dark blue-gray token drifted');
  assert.equal(rootStyle.getPropertyValue('--highlight').trim(),'#ad5944','final v4 dark highlight token drifted');
  const rules=[...d.styleSheets].flatMap(sheet=>[...sheet.cssRules]);
  const finalRule=selector=>rules.filter(rule=>rule.selectorText===selector).at(-1)?.style;
  assert.equal(finalRule(':root[data-theme="dark"] #alarmList .alarm-row.next-alarm')?.background,'#171a17','next alarm does not use the final card surface');
  const heroRule=finalRule(':root[data-theme="dark"] .insights-hero');
  assert.equal(heroRule?.background,'var(--bluegray)','Insights hero does not use final blue-gray treatment');
  assert.equal(heroRule?.getPropertyValue('box-shadow'),'none','Insights hero retained a superseded glow');
  assert.equal(finalRule('.insights-calendar')?.background,'var(--card)','Insights calendar does not use the final card treatment');
  assert.doesNotMatch(source,/appearanceMedia\.addEventListener|\['system','light','dark'\]/);
  assert.equal(d.documentElement.dataset.theme,'dark');
  assert.equal(d.documentElement.dataset.themePreference,'dark');
  assert.equal(d.getElementById('appearanceStatus').textContent,'Dark');
  assert.equal(d.querySelector('meta[name="theme-color"]').content,'#000000');
  assert.equal(d.querySelector('meta[name="apple-mobile-web-app-status-bar-style"]').content,'black-translucent');
  d.getElementById('appearanceSetting').click();
  assert.equal(d.documentElement.dataset.themePreference,'light');
  assert.equal(d.documentElement.dataset.theme,'light');
  assert.equal(d.getElementById('appearanceStatus').textContent,'Light');
  assert.equal(dom.window.localStorage.getItem('dreamworld:appearance'),'light');
  assert.equal(d.querySelector('meta[name="theme-color"]').content,'#ffffff');
  assert.equal(d.querySelector('meta[name="apple-mobile-web-app-status-bar-style"]').content,'default');
  d.getElementById('appearanceSetting').click();
  assert.equal(d.documentElement.dataset.theme,'dark');
  assert.equal(d.getElementById('appearanceStatus').textContent,'Dark');
  assert.equal(dom.window.localStorage.getItem('dreamworld:appearance'),'dark');
  assert.deepEqual(errors,[]);
  console.log('DREAMWORLD_DARK_MODE_VERIFIED');
  dom.window.close();
})().catch(error=>{console.error(error);dom.window.close();process.exitCode=1});